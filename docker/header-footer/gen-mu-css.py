"""Generates tienda/wp-content/mu-plugins/arbicop-shared-header.css from the two Elementor kit CSS dumps
(root-kit-45.css, shop-kit-13.css): the root kit's global variables re-declared inside the header/footer locations,
shop-only variables reset with `initial`, plus the root kit's container defaults."""
import re
H = 'docker/header-footer/'
root = open(H + 'root-kit-45.css', encoding='utf8').read(); shop = open(H + 'shop-kit-13.css', encoding='utf8').read()
scope = '.elementor-location-header,.elementor-location-footer'
def blocks(css, kit):
    """-> list of (media_prefix, declarations) for .elementor-kit-N blocks"""
    out = []
    for m in re.finditer(r'(?:(@media[^{]*)\{\s*)?\.elementor-kit-%d\{([^}]*)\}' % kit, css):
        if '--e-global' in m.group(2): out.append((m.group(1) or '', m.group(2)))
    return out
rb, sb = blocks(root, 45), blocks(shop, 13)
rootvars = set(re.findall(r'(--e-global-[a-z0-9-]+):', ' '.join(d for _, d in rb)))
out = ['/* Generated by docker/header-footer/gen-mu-css.py. Root kit globals scoped to the header/footer locations. */']
for media, decl in rb:
    out.append((media + '{' if media else '') + scope + '{' + decl + '}' + ('}' if media else ''))

# element rules of the root kit (h1-h6, a, buttons...) -> same rules scoped to the header/footer locations
css = re.sub(r'/\*.*?\*/', '', root, flags=re.S)
for m in re.finditer(r'(@media[^{]*)?\{?\s*((?:\.elementor-kit-45 [^{},]+,?)+)\{([^}]*)\}', css):
    pass
def rules(css):
    pos = 0; media = None; depth = 0
    for m in re.finditer(r'(@media[^{]*)\{|([^{}]+)\{([^}]*)\}|\}', css):
        if m.group(1): media = m.group(1); continue
        if m.group(2) is None:
            media = None; continue
        sel, body = m.group(2).strip(), m.group(3)
        if not re.match(r'\.elementor-kit-45 ', sel): continue
        parts = []
        for part in sel.split(','):
            part = part.strip()
            if part.startswith('.elementor-kit-45 '):
                for loc in ('.elementor-location-header', '.elementor-location-footer'):
                    parts.append(part.replace('.elementor-kit-45', loc, 1))
        yield media, ','.join(parts), body
for media, sel, body in rules(css):
    out.append((media + '{' if media else '') + sel + '{' + body + '}' + ('}' if media else ''))
resets = sorted({v for _, d in sb for v in re.findall(r'(--e-global-[a-z0-9-]+):', d)} - rootvars)
out.append(scope + '{' + ';'.join(v + ':initial' for v in resets) + '}')
out.append('''.elementor-location-header .elementor-element,.elementor-location-footer .elementor-element{--widgets-spacing:0px 0px;--widgets-spacing-row:0px;--widgets-spacing-column:0px}
.elementor-location-header .elementor-widget:not(:last-child),.elementor-location-footer .elementor-widget:not(:last-child){--kit-widget-spacing:0px}
.elementor-location-header .e-con,.elementor-location-footer .e-con{--container-max-width:1340px;--container-default-padding-top:0px;--container-default-padding-right:0px;--container-default-padding-bottom:0px;--container-default-padding-left:0px}
@media(max-width:1024px){.elementor-location-header .e-con,.elementor-location-footer .e-con{--container-max-width:97%}}
@media(max-width:767px){.elementor-location-header .e-con,.elementor-location-footer .e-con{--container-max-width:95%}}''')
open('tienda/wp-content/mu-plugins/arbicop-shared-header.css', 'w', encoding='utf8').write('\n'.join(out) + '\n')
print('root blocks', len(rb), 'shop blocks', len(sb), 'resets', len(resets))
